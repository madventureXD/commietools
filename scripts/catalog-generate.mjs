import { existsSync, mkdirSync, readFileSync, readdirSync, rmSync, writeFileSync } from 'node:fs'
import { dirname, join, relative, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'
import ts from 'typescript'

/**
 * Builds the searchable tool catalogue from the manifests and the locale
 * catalogues. The output is checked into the repository so the app can import
 * it without a network round trip; `check` fails as soon as it is out of date.
 *
 * Usage: node scripts/catalog-generate.mjs generate|check
 */
const root = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const mode = process.argv[2] ?? 'check'
const toolsSrc = join(root, 'packages', 'tools', 'src')
const corePath = join(root, 'packages', 'core', 'src', 'index.ts')
const manifestsPath = join(toolsSrc, 'catalog', 'manifests.ts')
const iconsDir = join(root, 'apps', 'web', 'public', 'tools')
const outputPath = join(toolsSrc, 'catalog', 'toolIndex.ts')
const generatedDir = join(toolsSrc, 'catalog', 'generated')
const searchDir = join(generatedDir, 'search')
const messagesDir = join(generatedDir, 'messages')
const loadersPath = join(generatedDir, 'loaders.ts')
const textLoadersPath = join(generatedDir, 'textLoaders.ts')
const banner = [
  '// Generated by scripts/catalog-generate.mjs - do not edit by hand.',
  '// Run `npm run catalog:generate` after changing manifests, locale catalogues or tool icons.',
  '',
  ''
].join('\n')

function fail(message) {
  console.error(`Catalogue audit failed: ${message}`)
  process.exit(1)
}

function toPosix(path) {
  return relative(root, path).split('\\').join('/')
}

/** Loads a dependency-free TypeScript module by compiling it in memory. */
async function loadModule(path) {
  const source = readFileSync(path, 'utf8')
  const { outputText } = ts.transpileModule(source, {
    compilerOptions: { module: ts.ModuleKind.ESNext, target: ts.ScriptTarget.ES2022 }
  })
  return import(`data:text/javascript;base64,${Buffer.from(outputText, 'utf8').toString('base64')}`)
}

/** Loads a module that exports exactly one object, regardless of its name. */
async function loadCatalogue(path) {
  const module = await loadModule(path)
  const names = Object.keys(module)
  if (names.length !== 1) fail(`${toPosix(path)} must export exactly one catalogue object, found ${names.length}`)
  return module[names[0]]
}

function collectLocaleFiles(directory) {
  const files = []
  for (const entry of readdirSync(directory, { withFileTypes: true })) {
    const path = join(directory, entry.name)
    if (entry.isDirectory()) {
      if (entry.name === 'node_modules') continue
      files.push(...collectLocaleFiles(path))
    } else if (directory.endsWith('locales') && entry.name.endsWith('.ts') && entry.name !== 'index.ts') {
      files.push(path)
    }
  }
  return files
}

const { knownFormats } = await loadModule(corePath)
const { toolManifests, suiteManifests } = await loadModule(manifestsPath)
const formatByMime = new Map(knownFormats.map((format) => [format.mime, format]))

if (!toolManifests.length) fail('no tool manifests found')

// --- locale catalogues -------------------------------------------------------

const localeFiles = collectLocaleFiles(toolsSrc).sort()
if (!localeFiles.length) fail('no locale catalogues found under packages/tools/src/**/locales')

const languagesByDirectory = new Map()
for (const path of localeFiles) {
  const directory = dirname(path)
  const language = path.slice(directory.length + 1, -'.ts'.length)
  if (!languagesByDirectory.has(directory)) languagesByDirectory.set(directory, new Set())
  languagesByDirectory.get(directory).add(language)
}
const languageSet = new Set([...languagesByDirectory.values()][0])
for (const [directory, languages] of languagesByDirectory) {
  const missing = [...languageSet].filter((language) => !languages.has(language))
  const extra = [...languages].filter((language) => !languageSet.has(language))
  if (missing.length || extra.length) {
    fail(`${toPosix(directory)} has an inconsistent language set${missing.length ? ` (missing: ${missing.join(', ')})` : ''}${extra.length ? ` (extra: ${extra.join(', ')})` : ''}`)
  }
}
const languages = [...languageSet].sort()

const catalogues = Object.fromEntries(languages.map((language) => [language, {}]))
for (const path of localeFiles) {
  const directory = dirname(path)
  const language = path.slice(directory.length + 1, -'.ts'.length)
  const catalogue = await loadCatalogue(path)
  for (const [key, value] of Object.entries(catalogue)) {
    if (key in catalogues[language]) fail(`duplicate key "${key}" in language "${language}" (${toPosix(path)})`)
    catalogues[language][key] = value
  }
}

// --- validation --------------------------------------------------------------

const seenIds = new Set()
const seenRoutes = new Set()
const suiteIdsByTool = new Map(toolManifests.map((tool) => [tool.id, []]))

for (const suite of suiteManifests) {
  for (const toolId of suite.toolIds) {
    if (!suiteIdsByTool.has(toolId)) fail(`suite "${suite.id}" references unknown tool "${toolId}"`)
    suiteIdsByTool.get(toolId).push(suite.id)
  }
}

function requireKey(tool, language, key, purpose) {
  const value = catalogues[language][key]
  if (typeof value !== 'string' || !value.trim()) {
    fail(`tool "${tool.id}" has no ${purpose} in language "${language}" (expected key "${key}")`)
  }
  return value
}

function requireMime(tool, mime, field) {
  if (!formatByMime.has(mime)) {
    fail(`tool "${tool.id}" declares unknown ${field} type "${mime}" - add it to knownFormats in packages/core`)
  }
}

for (const tool of toolManifests) {
  if (seenIds.has(tool.id)) fail(`duplicate tool id "${tool.id}"`)
  if (seenRoutes.has(tool.route)) fail(`duplicate tool route "${tool.route}"`)
  seenIds.add(tool.id)
  seenRoutes.add(tool.route)

  if (tool.route !== `/tools/${tool.id}`) fail(`tool "${tool.id}" must use route "/tools/${tool.id}", found "${tool.route}"`)

  for (const [field, purpose] of [['titleKey', 'title'], ['descriptionKey', 'description'], ['summaryKey', 'summary'], ['termsKey', 'terms']]) {
    if (typeof tool[field] !== 'string' || !tool[field]) fail(`tool "${tool.id}" is missing ${field}`)
    for (const language of languages) requireKey(tool, language, tool[field], purpose)
  }

  for (const language of languages) {
    const raw = requireKey(tool, language, tool.termsKey, 'terms')
    const list = raw.split(',').map((term) => term.trim()).filter(Boolean)
    if (!list.length) fail(`tool "${tool.id}" has empty search terms in language "${language}"`)
    const tags = list.filter((term) => term.startsWith('#'))
    if (!tags.length) fail(`tool "${tool.id}" has no tag (a term written with a leading "#") in language "${language}"`)
    if (tags.some((tag) => tag === '#')) fail(`tool "${tool.id}" has an empty tag in language "${language}"`)
    const seen = new Set()
    for (const term of list) {
      const normalized = term.toLowerCase()
      if (seen.has(normalized)) fail(`tool "${tool.id}" repeats the search term "${term}" in language "${language}"`)
      seen.add(normalized)
    }
  }

  const files = tool.files ?? {}
  const input = files.input ?? []
  const output = files.output ?? []
  const auxiliary = files.auxiliary ?? []
  for (const mime of input) requireMime(tool, mime, 'input')
  for (const mime of output) requireMime(tool, mime, 'output')
  const roles = new Set()
  for (const extra of auxiliary) {
    if (!extra.role) fail(`tool "${tool.id}" declares an auxiliary input without a role`)
    if (roles.has(extra.role)) fail(`tool "${tool.id}" declares the auxiliary role "${extra.role}" twice`)
    roles.add(extra.role)
    if (!extra.mimeTypes?.length) fail(`tool "${tool.id}" declares no types for auxiliary role "${extra.role}"`)
    for (const mime of extra.mimeTypes) requireMime(tool, mime, `auxiliary "${extra.role}"`)
  }
  if ((tool.category === 'image' || tool.category === 'pdf') && !input.length) {
    fail(`tool "${tool.id}" has category "${tool.category}" and must declare at least one input file type`)
  }

  if (!existsSync(join(iconsDir, `${tool.id}.svg`))) {
    fail(`tool "${tool.id}" has no icon at apps/web/public/tools/${tool.id}.svg`)
  }
}

// --- generated entry list ----------------------------------------------------

// File inputs must take their accept list from the manifest, never from a typed
// literal, so the declaration and the interface cannot drift apart.
const toolUiDir = join(root, 'apps', 'web', 'src', 'tools')
if (existsSync(toolUiDir)) {
  const offenders = readdirSync(toolUiDir)
    .filter((name) => name.endsWith('.tsx'))
    .filter((name) => /accept="/.test(readFileSync(join(toolUiDir, name), 'utf8')))
  if (offenders.length) fail(`file inputs must derive accept from the manifest, found a literal in: ${offenders.join(', ')}`)
}

const entries = toolManifests.map((tool) => {
  const files = tool.files ?? {}
  const locales = {}
  for (const language of languages) {
    const raw = requireKey(tool, language, tool.termsKey, 'terms')
    const list = raw.split(',').map((term) => term.trim()).filter(Boolean)
    locales[language] = {
      title: catalogues[language][tool.titleKey],
      summary: catalogues[language][tool.summaryKey],
      description: catalogues[language][tool.descriptionKey],
      terms: list.filter((term) => !term.startsWith('#')),
      tags: list.filter((term) => term.startsWith('#'))
    }
  }
  return {
    id: tool.id,
    route: tool.route,
    icon: `/tools/${tool.id}.svg`,
    category: tool.category,
    suiteIds: suiteIdsByTool.get(tool.id) ?? [],
    executionMode: tool.executionMode,
    resourceClass: tool.resourceClass,
    worksOffline: tool.worksOffline,
    input: files.input ?? [],
    output: files.output ?? [],
    auxiliary: files.auxiliary ?? [],
    locales
  }
})

const baseEntries = entries.map(({ locales: _locales, ...entry }) => entry)
const fileText = `${banner}import type { ToolCatalogEntry } from '@commietools/core'\n\nexport const toolIndex: readonly ToolCatalogEntry[] = ${JSON.stringify(baseEntries, null, 2)}\n`
const searchFiles = Object.fromEntries(languages.map((language) => [language, `${banner}import type { ToolLocaleEntry } from '@commietools/core'\n\nexport const searchLocale: Readonly<Record<string, ToolLocaleEntry>> = ${JSON.stringify(Object.fromEntries(entries.map((entry) => [entry.id, entry.locales[language]])), null, 2)}\n`]))
// Werkzeugtexte liegen **je Werkzeug** und **je Sprache** (Entscheidung 2026-10-05). Im Suchpaket
// stehen Titel, Kurztext, Beschreibung und Suchbegriffe; im Textpaket bleibt nur, was die
// Werkzeugoberfläche selbst braucht. Schlüssel ohne Werkzeugbezug — Rahmen- und Bereichstexte wie
// `tool.calc.*` (Rechnerrahmen), `tool.pdf.*` oder `tool.craft.*` — kommen in ein gemeinsames Paket
// je Sprache, das jede Werkzeugroute mitlädt. Die Regel steht in
// `uebergabe/02-architektur/sprachpakete.md`.
const prefixOfTool = (tool) => (tool.titleKey.endsWith('.title') ? tool.titleKey.slice(0, -'.title'.length) : null)
const toolPrefixes = toolManifests
  .map((tool) => ({ id: tool.id, prefix: prefixOfTool(tool) }))
  .filter((entry) => Boolean(entry.prefix))
  // Längster Präfix gewinnt: `tool.pdfPlacement.watermark` schlägt ein denkbares `tool.pdfPlacement`.
  .sort((left, right) => right.prefix.length - left.prefix.length)
const catalogueKeys = new Set(toolManifests.flatMap((tool) => [tool.titleKey, tool.descriptionKey, tool.summaryKey, tool.termsKey]))
const toolTextPackages = Object.fromEntries(languages.map((language) => {
  const byTool = new Map(toolPrefixes.map((entry) => [entry.id, {}]))
  const common = {}
  for (const [key, value] of Object.entries(catalogues[language])) {
    if (catalogueKeys.has(key)) continue
    const owner = toolPrefixes.find((entry) => key.startsWith(`${entry.prefix}.`))
    if (owner) byTool.get(owner.id)[key] = value
    else common[key] = value
  }
  return [language, { byTool, common }]
}))
const textFile = (messages) => `${banner}export const messages: Readonly<Record<string, string>> = ${JSON.stringify(messages, null, 2)}\n`
const loaderCases = languages.map((language) => `  ${JSON.stringify(language)}: () => import('./search/${language}'),`).join('\n')
const textLoaderCases = languages.map((language) => {
  const tools = toolPrefixes.map((entry) => `    ${JSON.stringify(entry.id)}: () => import('./messages/${language}/${entry.id}'),`).join('\n')
  return `  ${JSON.stringify(language)}: {\n    common: () => import('./messages/${language}/common'),\n${tools}\n  },`
}).join('\n')
const loadersText = `${banner}import { cachedLoader } from '@commietools/core/loadCache'
import type { ToolSearchEntry } from '@commietools/core'
import { toolIndex } from '../toolIndex'

const searchLoaders = {
${loaderCases}
} as const
export type GeneratedLocale = keyof typeof searchLoaders
const searchCache = new Map<string, Promise<readonly ToolSearchEntry[]>>()

export function loadToolSearchIndex(locale: GeneratedLocale): Promise<readonly ToolSearchEntry[]> {
  const key = locale === 'en' ? 'en' : \`\${locale}+en\`
  return cachedLoader(searchCache, key, () => (locale === 'en'
    ? searchLoaders.en().then((english) => toolIndex.map((entry) => ({ ...entry, locales: { en: english.searchLocale[entry.id]! } })))
    : Promise.all([searchLoaders.en(), searchLoaders[locale]()]).then(([english, selected]) => toolIndex.map((entry) => ({ ...entry, locales: { [locale]: selected.searchLocale[entry.id]!, en: english.searchLocale[entry.id]! } })))))
}
`

/**
 * Die Werkzeugtexte liegen in einer **eigenen** Datei. Grund: die Verweiskarte ueber 147
 * nachgeladene Pakete ist rund 2,6 kB gzip gross. Laege sie im Eingang, zahlte die Startseite
 * sie bei jedem Besuch mit, obwohl sie dort nie gebraucht wird — sie wird erst auf einer
 * Werkzeugroute geholt.
 */
const textLoadersText = `${banner}import { cachedLoader } from '@commietools/core/loadCache'
import type { GeneratedLocale } from './loaders'

const textLoaders = {
${textLoaderCases}
} as const
type TextLoader = () => Promise<{ messages: Readonly<Record<string, string>> }>
type LocaleTexts = Readonly<Record<string, Readonly<Record<string, string>>>>
const textCache = new Map<string, Promise<LocaleTexts>>()
const toolsOf = (locale: GeneratedLocale): Record<string, TextLoader> => textLoaders[locale] as unknown as Record<string, TextLoader>
const empty: TextLoader = () => Promise.resolve({ messages: {} })
/** Englisch zuerst, die gewaehlte Sprache darueber — genau die Reihenfolge, die der Uebersetzer aufloest. */
const pair = (locale: GeneratedLocale, load: (language: GeneratedLocale) => Promise<Readonly<Record<string, string>>>): Promise<LocaleTexts> =>
  locale === 'en' ? load('en').then((english) => ({ en: english })) : Promise.all([load('en'), load(locale)]).then(([english, selected]) => ({ en: english, [locale]: selected }))

/** Gemeinsame Werkzeugtexte einer Sprache: Rahmen und Bereiche (tool.calc.*, tool.pdf.*, ...). */
export function loadCommonToolTexts(locale: GeneratedLocale): Promise<LocaleTexts> {
  const key = \`common:\${locale}\`
  return cachedLoader(textCache, key, () => pair(locale, (language) => textLoaders[language].common().then((module) => module.messages)))
}

/** Die Texte EINES Werkzeugs: gemeinsame Texte plus dieses Werkzeug, dazu Englisch. */
export function loadToolTexts(locale: GeneratedLocale, toolId: string): Promise<LocaleTexts> {
  const key = \`\${locale}:\${toolId}\`
  return cachedLoader(textCache, key, () => pair(locale, (language) => Promise.all([textLoaders[language].common(), (toolsOf(language)[toolId] ?? empty)()]).then(([common, own]) => ({ ...common.messages, ...own.messages }))))
}

/** Alle Werkzeugtexte einer Sprache — fuer Pruefungen und Pruefwerkzeuge, nicht fuer die Oberflaeche. */
export function loadAllToolTexts(locale: GeneratedLocale): Promise<LocaleTexts> {
  const key = \`all:\${locale}\`
  return cachedLoader(textCache, key, () => pair(locale, (language) => {
    const own = Object.entries(toolsOf(language)).filter(([id]) => id !== 'common').map(([, loader]) => loader())
    return Promise.all([textLoaders[language].common(), ...own]).then(([common, ...rest]) => Object.assign({}, common.messages, ...rest.map((module) => module.messages)))
  }))
}
`

const declaredFileTypes = (entry) => entry.input.length + entry.output.length + entry.auxiliary.reduce((total, extra) => total + extra.mimeTypes.length, 0)
const canonicalText = (value) => value.replace(/\r\n/gu, '\n')

if (mode === 'generate') {
  mkdirSync(searchDir, { recursive: true }); mkdirSync(messagesDir, { recursive: true })
  writeFileSync(outputPath, fileText, 'utf8')
  for (const language of languages) {
    writeFileSync(join(searchDir, `${language}.ts`), searchFiles[language], 'utf8')
    const languageDir = join(messagesDir, language)
    mkdirSync(languageDir, { recursive: true })
    const expectedNames = new Set(['common.ts', ...toolPrefixes.map((entry) => `${entry.id}.ts`)])
    // Eine Datei, die keinem Werkzeug mehr gehört, muss weg — sonst bleibt sie für immer liegen.
    for (const name of readdirSync(languageDir)) if (name.endsWith('.ts') && !expectedNames.has(name)) rmSync(join(languageDir, name))
    writeFileSync(join(languageDir, 'common.ts'), textFile(toolTextPackages[language].common), 'utf8')
    for (const entry of toolPrefixes) writeFileSync(join(languageDir, `${entry.id}.ts`), textFile(toolTextPackages[language].byTool.get(entry.id) ?? {}), 'utf8')
  }
  writeFileSync(loadersPath, loadersText, 'utf8')
  writeFileSync(textLoadersPath, textLoadersText, 'utf8')
  const termCount = entries.reduce((total, entry) => total + Object.values(entry.locales).reduce((sum, locale) => sum + locale.terms.length + locale.tags.length, 0), 0)
  console.log(`Catalogue written: ${toPosix(outputPath)}`)
  console.log(`${entries.length} tools, ${languages.length} languages (${languages.join(', ')}), ${termCount} search terms, ${entries.reduce((total, entry) => total + declaredFileTypes(entry), 0)} declared file types`)
} else if (mode === 'check') {
  if (!existsSync(outputPath)) fail(`${toPosix(outputPath)} is missing - run npm run catalog:generate`)
  const current = canonicalText(readFileSync(outputPath, 'utf8'))
  if (current !== canonicalText(fileText)) {
    const currentLines = current.split('\n')
    const expectedLines = fileText.split('\n')
    const index = currentLines.findIndex((line, position) => line !== expectedLines[position])
    const hint = index === -1
      ? `line count differs (${currentLines.length} vs ${expectedLines.length})`
      : `first difference on line ${index + 1}:\n  now:      ${currentLines[index] ?? '<end of file>'}\n  expected: ${expectedLines[index] ?? '<end of file>'}`
    fail(`${toPosix(outputPath)} is out of date - run npm run catalog:generate\n  ${hint}`)
  }
  for (const language of languages) {
    const expectedFiles = [
      [join(searchDir, `${language}.ts`), searchFiles[language]],
      [join(messagesDir, language, 'common.ts'), textFile(toolTextPackages[language].common)],
      ...toolPrefixes.map((entry) => [join(messagesDir, language, `${entry.id}.ts`), textFile(toolTextPackages[language].byTool.get(entry.id) ?? {})])
    ]
    for (const [path, expected] of expectedFiles) {
      if (!existsSync(path) || canonicalText(readFileSync(path, 'utf8')) !== canonicalText(expected)) fail(`${toPosix(path)} is out of date - run npm run catalog:generate`)
    }
    // Eine Datei, die keinem Werkzeug mehr gehört, muss auffallen — sonst bleibt sie liegen.
    const expectedNames = new Set(['common.ts', ...toolPrefixes.map((entry) => `${entry.id}.ts`)])
    const languageDir = join(messagesDir, language)
    if (existsSync(languageDir)) for (const name of readdirSync(languageDir)) if (name.endsWith('.ts') && !expectedNames.has(name)) fail(`${toPosix(join(languageDir, name))} belongs to no tool - run npm run catalog:generate`)
  }
  if (!existsSync(loadersPath) || canonicalText(readFileSync(loadersPath, 'utf8')) !== canonicalText(loadersText)) fail(`${toPosix(loadersPath)} is out of date - run npm run catalog:generate`)
  if (!existsSync(textLoadersPath) || canonicalText(readFileSync(textLoadersPath, 'utf8')) !== canonicalText(textLoadersText)) fail(`${toPosix(textLoadersPath)} is out of date - run npm run catalog:generate`)
  console.log(`Catalogue check passed: ${entries.length} tools, ${languages.length} languages (${languages.join(', ')}), ${entries.length} icons, ${entries.reduce((total, entry) => total + declaredFileTypes(entry), 0)} declared file types`)
} else {
  fail(`unknown mode "${mode}" - use generate or check`)
}
